// The wrap wiring: harbor wrap add rewrites a client's stdio MCP entry to
// spawn harbor-wrap around the original server command. The policy stays
// name-keyed and local (the wrapper never needs the server), and the
// original entry is preserved in the import state so remove can restore it.

const wrapTemplate = `# harbor.yaml - generated by harbor wrap add.
# The circle is open mode: wrapped tools keep working; tighten with deny
# rules or flip strict when the audit timeline shows what to lock.
version: 1

workspaces:
  - id: main
    strict: false
    targets:
%s
agents:
%s
`

func cmdWrap(args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		fmt.Fprintln(stderr, "harbor wrap: expected add or remove")
		return 2
	}
	subcommand, rest := args[0], args[1:]
	switch subcommand {
	case "add":
		return cmdWrapAdd(rest, stdout, stderr)
	case "remove":
		return cmdWrapRemove(rest, stdout, stderr)
	default:
		fmt.Fprintf(stderr, "harbor wrap: unknown subcommand %q\n", subcommand)
		return 2
	}
}

func cmdWrapAdd(args []string, stdout, stderr io.Writer) int {
	flags := newFlagSet("wrap add", stderr)
	wrapBin := flags.String("wrap-bin", defaultWrapBin(), "harbor-wrap binary the client will spawn")
	policyPath := flags.String("policy", defaultPolicyPath(), "harbor.yaml to extend")
	statePath := flags.String("state", defaultStateFile, "import state file")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	rest := flags.Args()
	if len(rest) != 2 {
		fmt.Fprintln(stderr, "harbor wrap add: exactly a client key and a server name required")
		fmt.Fprintln(stderr, "usage: harbor wrap add <client> <name> [--wrap-bin PATH] [--policy FILE]")
		return 2
	}
	clientKey, name := rest[0], rest[1]
	spec, err := clients.Find(clientKey)
	if err != nil {
		fmt.Fprintf(stderr, "harbor wrap add: %v\n", err)
		return 2
	}
	if !spec.Writable {
		fmt.Fprintf(stderr, "harbor wrap add: %s configs are print-only for now\n", spec.DisplayName)
		return 2
	}
	configPath := spec.ExistingConfigPath()
	if configPath == "" {
		fmt.Fprintf(stderr, "harbor wrap add: no config file found for %s\n", spec.Key)
		return 2
	}
	entry, err := readMCPEntry(configPath, name)
	if err != nil {
		fmt.Fprintf(stderr, "harbor wrap add: %v\n", err)
		return 2
	}
	command, _ := entry["command"].(string)
	if strings.TrimSpace(command) == "" {
		fmt.Fprintf(stderr, "harbor wrap add: server %q has no command (only stdio servers can be wrapped)\n", name)
		return 2
	}
	if _, err := os.Stat(*wrapBin); err != nil {
		fmt.Fprintf(stderr, "harbor wrap add: --wrap-bin %s not found (build it: go build -o %s ./cmd/harbor-wrap)\n", *wrapBin, *wrapBin)
		return 2
	}

	state, err := loadOrCreateWrapState(*statePath)
	if err != nil {
		fmt.Fprintf(stderr, "harbor wrap add: %v\n", err)
		return 2
	}
	if isWrapped(state, clientKey, name) {
		fmt.Fprintf(stdout, "%s already wraps %s - nothing to do\n", clientKey, name)
		return 0
	}

	if err := ensureWrapPolicy(*policyPath, name, clientKey); err != nil {
		fmt.Fprintf(stderr, "harbor wrap add: %v\n", err)
		return 2
	}

	original, _ := json.Marshal(entry)
	wrappedArgs := append(
		[]string{"--agent", clientKey, "--target", name, "--", command},
		stringArgs(entry["args"])...,
	)
	if err := rewriteMCPEntry(configPath, name, map[string]any{
		"command": *wrapBin,
		"args":    wrappedArgs,
		"env":     entry["env"],
	}); err != nil {
		fmt.Fprintf(stderr, "harbor wrap add: %v\n", err)
		return 2
	}
	rememberWrapped(state, *statePath, clientKey, name, original)
	fmt.Fprintf(stdout, "wrapped %s on %s (config backed up; restart the client to take effect)\n", name, spec.DisplayName)
	fmt.Fprintf(stdout, "  policy: %s (target %s, agent %s)\n", *policyPath, name, clientKey)
	return 0
}

func cmdWrapRemove(args []string, stdout, stderr io.Writer) int {
	flags := newFlagSet("wrap remove", stderr)
	statePath := flags.String("state", defaultStateFile, "import state file")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	rest := flags.Args()
	if len(rest) != 2 {
		fmt.Fprintln(stderr, "harbor wrap remove: exactly a client key and a server name required")
		return 2
	}
	clientKey, name := rest[0], rest[1]
	spec, err := clients.Find(clientKey)
	if err != nil {
		fmt.Fprintf(stderr, "harbor wrap remove: %v\n", err)
		return 2
	}
	state, err := loadOrCreateWrapState(*statePath)
	if err != nil {
		fmt.Fprintf(stderr, "harbor wrap remove: %v\n", err)
		return 2
	}
	original, ok := wrappedOriginal(state, clientKey, name)
	if !ok {
		fmt.Fprintf(stderr, "harbor wrap remove: %s is not wrapped via this state file\n", name)
		return 2
	}
	configPath := spec.ExistingConfigPath()
	if configPath == "" {
		fmt.Fprintf(stderr, "harbor wrap remove: no config file found for %s\n", spec.Key)
		return 2
	}
	var entry map[string]any
	if err := json.Unmarshal(original, &entry); err != nil {
		fmt.Fprintf(stderr, "harbor wrap remove: stored original is unreadable: %v\n", err)
		return 2
	}
	if err := rewriteMCPEntry(configPath, name, entry); err != nil {
		fmt.Fprintf(stderr, "harbor wrap remove: %v\n", err)
		return 2
	}
	forgetWrapped(state, *statePath, clientKey, name)
	fmt.Fprintf(stdout, "restored %s on %s (restart the client to take effect)\n", name, spec.DisplayName)
	return 0
}

func readMCPEntry(configPath, name string) (map[string]any, error) {
	document, err := readJSONDocument(configPath)
	if err != nil {
		return nil, err
	}
	servers, _ := document["mcpServers"].(map[string]any)
	entry, ok := servers[name].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("server %q not found in %s", name, configPath)
	}
	return entry, nil
}

func rewriteMCPEntry(configPath, name string, entry map[string]any) error {
	document, err := readJSONDocument(configPath)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(configPath)
	if err != nil {
		return err
	}
	servers, ok := document["mcpServers"].(map[string]any)
	if !ok {
		servers = map[string]any{}
		document["mcpServers"] = servers
	}
	backup, err := os.Create(configPath + ".harbor.bak")
	if err != nil {
		return fmt.Errorf("backup: %w", err)
	}
	if _, err := backup.Write(raw); err != nil {
		backup.Close()
		return fmt.Errorf("backup: %w", err)
	}
	backup.Close()
	servers[name] = entry
	encoded, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(configPath, encoded, 0o644)
}

func readJSONDocument(configPath string) (map[string]any, error) {
	raw, err := os.ReadFile(configPath)
	if err != nil {
		return nil, err
	}
	var document map[string]any
	if err := json.Unmarshal(raw, &document); err != nil {
		return nil, fmt.Errorf("parse %s: %w", configPath, err)
	}
	if document == nil {
		document = map[string]any{}
	}
	return document, nil
}

// ensureWrapPolicy guarantees the name-keyed target and the client agent
// exist in harbor.yaml. A missing file is generated; an existing file is
// extended textually (anchors on the generated layout) and re-validated -
// on any surprise the original file is restored untouched and the operator
// gets the exact lines to add by hand.
func ensureWrapPolicy(path, name, clientKey string) error {
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		targets := fmt.Sprintf("      - id: %s\n", name)
		agents := fmt.Sprintf("  - id: %s\n    workspace: main\n", clientKey)
		generated := fmt.Sprintf(wrapTemplate, targets, agents)
		if _, err := policy.Parse(strings.NewReader(generated)); err != nil {
			return fmt.Errorf("generated policy invalid: %w", err)
		}
		return os.WriteFile(path, []byte(generated), 0o644)
	}
	if err != nil {
		return err
	}
	parsed, err := policy.Parse(strings.NewReader(string(raw)))
	if err != nil {
		return fmt.Errorf("existing policy does not parse: %w", err)
	}
	needTarget := !policyHasTarget(parsed, name)
	needAgent := !policyHasAgent(parsed, clientKey)
	if !needTarget && !needAgent {
		return nil
	}
	extended := string(raw)
	if needTarget {
		anchor := "    targets:\n"
		if !strings.Contains(extended, anchor) {
			return manualAddError(name, clientKey)
		}
		extended = strings.Replace(extended, anchor, anchor+fmt.Sprintf("      - id: %s\n", name), 1)
	}
	if needAgent {
		if !strings.Contains(extended, "agents:\n") {
			return manualAddError(name, clientKey)
		}
		extended = strings.Replace(extended, "agents:\n", fmt.Sprintf("agents:\n  - id: %s\n    workspace: main\n", clientKey), 1)
	}
	if _, err := policy.Parse(strings.NewReader(extended)); err != nil {
		return manualAddError(name, clientKey)
	}
	return os.WriteFile(path, []byte(extended), 0o644)
}

func manualAddError(name, clientKey string) error {
	return fmt.Errorf("could not extend harbor.yaml automatically; add manually:\n      - id: %s   # under the workspace targets\n  - id: %s\n    workspace: main   # under agents", name, clientKey)
}

func policyHasTarget(parsed *policy.Policy, name string) bool {
	for _, workspace := range parsed.Workspaces {
		for _, target := range workspace.Targets {
			if target.ID == name {
				return true
			}
		}
	}
	return false
}

func policyHasAgent(parsed *policy.Policy, clientKey string) bool {
	for _, agent := range parsed.Agents {
		if agent.ID == clientKey {
			return true
		}
	}
	return false
}

// wrap state rides on the import state file with a dedicated section.

type wrapState struct {
	Wrapped map[string]map[string]json.RawMessage `json:"wrapped"` // client -> name -> original entry
}

func loadOrCreateWrapState(path string) (wrapState, error) {
	state := wrapState{Wrapped: map[string]map[string]json.RawMessage{}}
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return state, nil
	}
	if err != nil {
		return state, err
	}
	if err := json.Unmarshal(raw, &state); err != nil {
		return state, fmt.Errorf("parse %s: %w", path, err)
	}
	if state.Wrapped == nil {
		state.Wrapped = map[string]map[string]json.RawMessage{}
	}
	return state, nil
}

func saveWrapState(path string, state wrapState) error {
	encoded, err := json.MarshalIndent(state, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, encoded, 0o644)
}

func isWrapped(state wrapState, clientKey, name string) bool {
	_, ok := state.Wrapped[clientKey][name]
	return ok
}

func rememberWrapped(state wrapState, path, clientKey, name string, original []byte) {
	clients, ok := state.Wrapped[clientKey]
	if !ok {
		clients = map[string]json.RawMessage{}
		state.Wrapped[clientKey] = clients
	}
	clients[name] = json.RawMessage(original)
	_ = saveWrapState(path, state)
}

func forgetWrapped(state wrapState, path, clientKey, name string) {
	if clients, ok := state.Wrapped[clientKey]; ok {
		delete(clients, name)
		if len(clients) == 0 {
			delete(state.Wrapped, clientKey)
		}
	}
	_ = saveWrapState(path, state)
}

func wrappedOriginal(state wrapState, clientKey, name string) (json.RawMessage, bool) {
	original, ok := state.Wrapped[clientKey][name]
	return original, ok
}

func stringArgs(raw any) []string {
	values, _ := raw.([]any)
	out := make([]string, 0, len(values))
	for _, value := range values {
		if text, ok := value.(string); ok {
			out = append(out, text)
		}
	}
	return out
}

func defaultWrapBin() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".harbor", "bin", "harbor-wrap")
}

func defaultPolicyPath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".harbor", "harbor.yaml")
}
