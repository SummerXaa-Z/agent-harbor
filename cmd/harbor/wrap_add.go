// The wrap wiring: harbor wrap add rewrites a client's stdio MCP entry to
// spawn harbor-wrap around the original server command. The policy stays
// name-keyed and local (the wrapper never needs the server), and the
// original entry is preserved in dedicated wrap state so remove can restore it.

const wrapTemplate = `# harbor.yaml - generated by harbor wrap add.
# The circle is open mode: wrapped tools keep working; tighten with deny
# rules or flip strict when the audit timeline shows what to lock.
version: 1

workspaces:
  - id: main
    strict: false
    targets:
%s
agents:
%s
`

func cmdWrap(args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		fmt.Fprintln(stderr, "harbor wrap: expected add or remove")
		return 2
	}
	subcommand, rest := args[0], args[1:]
	switch subcommand {
	case "add":
		return cmdWrapAdd(rest, stdout, stderr)
	case "remove":
		return cmdWrapRemove(rest, stdout, stderr)
	default:
		fmt.Fprintf(stderr, "harbor wrap: unknown subcommand %q\n", subcommand)
		return 2
	}
}

func cmdWrapAdd(args []string, stdout, stderr io.Writer) int {
	flags := newFlagSet("wrap add", stderr)
	wrapBin := flags.String("wrap-bin", defaultWrapBin(), "harbor-wrap binary the client will spawn")
	policyPath := flags.String("policy", defaultPolicyPath(), "harbor.yaml to extend")
	statePath := flags.String("state", defaultWrapStatePath(), "dedicated wrap state file")
	agentID := flags.String("agent-id", "", "registered caller ID already declared in the local policy")
	targetID := flags.String("target-id", "", "registered target ID already declared in the caller workspace")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	rest := flags.Args()
	if len(rest) != 2 {
		fmt.Fprintln(stderr, "usage: harbor wrap add [--wrap-bin PATH] [--policy FILE] [--state FILE] [--agent-id ID --target-id ID] <client> <name>")
		return 2
	}
	if (*agentID == "") != (*targetID == "") {
		fmt.Fprintln(stderr, "harbor wrap add: --agent-id and --target-id must be supplied together")
		return 2
	}
	err := wrapAdd(rest[0], rest[1], *wrapBin, *policyPath, *statePath, *agentID, *targetID)
	if err != nil {
		fmt.Fprintf(stderr, "harbor wrap add: %v\n", err)
		return 2
	}
	fmt.Fprintf(stdout, "wrapped %s on %s (restart the client to take effect)\n", rest[1], rest[0])
	return 0
}

func wrapAdd(clientKey, name, wrapBin, policyPath, statePath, agentID, targetID string) error {
	bound := agentID != ""
	if !bound {
		agentID, targetID = clientKey, name
	}
	ensurePolicy := func(write wrapWriteFunc) error {
		if !bound {
			return ensureWrapPolicyWithWriter(policyPath, targetID, agentID, write)
		}
		parsed, err := policy.LoadFile(policyPath)
		if err != nil {
			return fmt.Errorf("registry binding requires an existing valid local policy: %w", err)
		}
		workspace, hasAgent := wrapAgentWorkspace(parsed, agentID)
		if !hasAgent || !wrapWorkspaceHasTarget(parsed, workspace, targetID) {
			return manualAddError(targetID, agentID)
		}
		return nil
	}
	configPath, err := wrapConfigPath(clientKey)
	if err != nil {
		return err
	}
	wrapBin, err = filepath.Abs(wrapBin)
	if err != nil {
		return err
	}
	policyPath, err = filepath.Abs(policyPath)
	if err != nil {
		return err
	}
	info, err := os.Stat(wrapBin)
	if err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0o111 == 0 {
		return fmt.Errorf("--wrap-bin must be an executable file")
	}
	return wrapTransaction([]string{configPath, configPath + ".harbor.bak", statePath, policyPath}, func(write wrapWriteFunc) error {
		entry, err := readMCPEntry(configPath, name)
		if err != nil {
			return err
		}
		state, err := loadOrCreateWrapState(statePath)
		if err != nil {
			return err
		}
		if record, ok := state.Wrapped[clientKey][name]; ok {
			if record.Config != configPath {
				return fmt.Errorf("state belongs to a different config; restore that config first")
			}
			if !sameWrapEntry(entry, record.Installed) {
				return fmt.Errorf("wrapped entry changed; refusing to overwrite it")
			}
			installedArgs := stringArgs(entry["args"])
			if record.Policy != policyPath || entry["command"] != wrapBin || len(installedArgs) < 6 || installedArgs[3] != agentID || installedArgs[5] != targetID {
				return fmt.Errorf("already wrapped with different options; remove first")
			}
			return ensurePolicy(write)
		}
		command, _ := entry["command"].(string)
		if strings.TrimSpace(command) == "" {
			return fmt.Errorf("server %q has no command (only stdio servers can be wrapped)", name)
		}
		if command == wrapBin || filepath.Base(command) == "harbor-wrap" {
			return fmt.Errorf("entry already uses harbor-wrap but has no matching state")
		}
		originalArgs, err := checkedWrapArgs(entry["args"])
		if err != nil {
			return err
		}
		original, err := json.Marshal(entry)
		if err != nil {
			return err
		}
		wrapped := make(map[string]any, len(entry))
		for key, value := range entry {
			wrapped[key] = value
		}
		wrapped["command"] = wrapBin
		wrapped["args"] = append([]string{"--policy", policyPath, "--agent", agentID, "--target", targetID, "--", command}, originalArgs...)
		installed, err := json.Marshal(wrapped)
		if err != nil {
			return err
		}
		if err := ensurePolicy(write); err != nil {
			return err
		}
		if state.Wrapped[clientKey] == nil {
			state.Wrapped[clientKey] = map[string]wrapRecord{}
		}
		state.Wrapped[clientKey][name] = wrapRecord{Config: configPath, Policy: policyPath, Original: original, Installed: installed}
		// Persist recovery data before replacing the client entry.
		if err := saveWrapState(statePath, state, write); err != nil {
			return err
		}
		return rewriteMCPEntry(configPath, name, wrapped, write)
	})
}

func cmdWrapRemove(args []string, stdout, stderr io.Writer) int {
	flags := newFlagSet("wrap remove", stderr)
	statePath := flags.String("state", defaultWrapStatePath(), "dedicated wrap state file")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	rest := flags.Args()
	if len(rest) != 2 {
		fmt.Fprintln(stderr, "usage: harbor wrap remove [--state FILE] <client> <name>")
		return 2
	}
	err := wrapRemove(rest[0], rest[1], *statePath)
	if err != nil {
		fmt.Fprintf(stderr, "harbor wrap remove: %v\n", err)
		return 2
	}
	fmt.Fprintf(stdout, "restored %s on %s (restart the client to take effect)\n", rest[1], rest[0])
	return 0
}

func wrapRemove(clientKey, name, statePath string) error {
	configPath, err := wrapConfigPath(clientKey)
	if err != nil {
		return err
	}
	return wrapTransaction([]string{configPath, configPath + ".harbor.bak", statePath}, func(write wrapWriteFunc) error {
		state, err := loadOrCreateWrapState(statePath)
		if err != nil {
			return err
		}
		record, ok := state.Wrapped[clientKey][name]
		if !ok {
			return fmt.Errorf("%s is not wrapped via this state file", name)
		}
		if record.Config != configPath {
			return fmt.Errorf("state belongs to a different config; refusing to restore")
		}
		current, err := readMCPEntry(configPath, name)
		if err != nil {
			return err
		}
		var original map[string]any
		if err := json.Unmarshal(record.Original, &original); err != nil {
			return err
		}
		if !sameWrapEntry(current, record.Original) {
			if !sameWrapEntry(current, record.Installed) {
				return fmt.Errorf("wrapped entry changed; refusing to overwrite it; reconcile manually")
			}
			if err := rewriteMCPEntry(configPath, name, original, write); err != nil {
				return err
			}
		}
		delete(state.Wrapped[clientKey], name)
		if len(state.Wrapped[clientKey]) == 0 {
			delete(state.Wrapped, clientKey)
		}
		return saveWrapState(statePath, state, write)
	})
}

func wrapConfigPath(clientKey string) (string, error) {
	spec, err := clients.Find(clientKey)
	if err != nil {
		return "", err
	}
	if !spec.Writable || spec.Format != clients.FormatMCPJSON {
		return "", fmt.Errorf("%s configs are print-only for now", spec.DisplayName)
	}
	path := spec.ExistingConfigPath()
	if path == "" {
		return "", fmt.Errorf("no config file found for %s", clientKey)
	}
	return filepath.Abs(path)
}

func checkedWrapArgs(raw any) ([]string, error) {
	if raw == nil {
		return nil, nil
	}
	values, ok := raw.([]any)
	if !ok {
		return nil, fmt.Errorf("server args must be an array of strings")
	}
	out := make([]string, len(values))
	for i, value := range values {
		text, ok := value.(string)
		if !ok {
			return nil, fmt.Errorf("server args must be an array of strings")
		}
		out[i] = text
	}
	return out, nil
}

func sameWrapEntry(entry map[string]any, raw json.RawMessage) bool {
	var expected map[string]any
	if json.Unmarshal(raw, &expected) != nil {
		return false
	}
	return reflect.DeepEqual(entry, expected)
}

func readMCPEntry(configPath, name string) (map[string]any, error) {
	document, err := readJSONDocument(configPath)
	if err != nil {
		return nil, err
	}
	servers, _ := document["mcpServers"].(map[string]any)
	entry, ok := servers[name].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("server %q not found in %s", name, configPath)
	}
	return entry, nil
}

func rewriteMCPEntry(configPath, name string, entry map[string]any, write wrapWriteFunc) error {
	document, err := readJSONDocument(configPath)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(configPath)
	if err != nil {
		return err
	}
	servers, ok := document["mcpServers"].(map[string]any)
	if !ok {
		servers = map[string]any{}
		document["mcpServers"] = servers
	}
	if err := write(configPath+".harbor.bak", raw); err != nil {
		return fmt.Errorf("backup: %w", err)
	}
	servers[name] = entry
	encoded, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		return err
	}
	return write(configPath, encoded)
}

func readJSONDocument(configPath string) (map[string]any, error) {
	raw, err := os.ReadFile(configPath)
	if err != nil {
		return nil, err
	}
	var document map[string]any
	if err := json.Unmarshal(raw, &document); err != nil {
		return nil, fmt.Errorf("parse %s: %w", configPath, err)
	}
	if document == nil {
		document = map[string]any{}
	}
	return document, nil
}

// Existing multi-workspace policies require explicit ownership decisions; never
// infer the destination from the first workspace or a globally matching target.
func ensureWrapPolicy(path, name, clientKey string) error {
	return ensureWrapPolicyWithWriter(path, name, clientKey, atomicWrapWrite)
}

func ensureWrapPolicyWithWriter(path, name, clientKey string, write wrapWriteFunc) error {
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		targets := fmt.Sprintf("      - id: %s\n", wrapPolicyScalar(name))
		agents := fmt.Sprintf("  - id: %s\n    workspace: main\n", wrapPolicyScalar(clientKey))
		generated := fmt.Sprintf(wrapTemplate, targets, agents)
		if _, err := policy.Parse(strings.NewReader(generated)); err != nil {
			return fmt.Errorf("generated policy invalid: %w", err)
		}
		return write(path, []byte(generated))
	}
	if err != nil {
		return err
	}
	parsed, err := policy.Parse(strings.NewReader(string(raw)))
	if err != nil {
		return fmt.Errorf("existing policy does not parse: %w", err)
	}
	workspaceID, agentExists := wrapAgentWorkspace(parsed, clientKey)
	if agentExists && wrapWorkspaceHasTarget(parsed, workspaceID, name) {
		return nil
	}
	if len(parsed.Workspaces) != 1 || parsed.Workspaces[0].ID != "main" {
		return manualAddError(name, clientKey)
	}
	needTarget := !wrapWorkspaceHasTarget(parsed, "main", name)
	needAgent := !agentExists
	extended := string(raw)
	if needTarget {
		anchor := "\n    targets:\n"
		if strings.Count(extended, anchor) != 1 {
			return manualAddError(name, clientKey)
		}
		extended = strings.Replace(extended, anchor, anchor+fmt.Sprintf("      - id: %s\n", wrapPolicyScalar(name)), 1)
	}
	if needAgent {
		anchor := "\nagents:\n"
		if strings.Count(extended, anchor) != 1 {
			return manualAddError(name, clientKey)
		}
		extended = strings.Replace(extended, anchor, anchor+fmt.Sprintf("  - id: %s\n    workspace: main\n", wrapPolicyScalar(clientKey)), 1)
	}
	updated, err := policy.Parse(strings.NewReader(extended))
	if err != nil {
		return manualAddError(name, clientKey)
	}
	workspaceID, agentExists = wrapAgentWorkspace(updated, clientKey)
	if !agentExists || workspaceID != "main" || !wrapWorkspaceHasTarget(updated, workspaceID, name) {
		return manualAddError(name, clientKey)
	}
	return write(path, []byte(extended))
}

func manualAddError(name, clientKey string) error {
	return fmt.Errorf("could not extend harbor.yaml automatically; manually declare agent %q in its intended workspace and target %q in that same workspace; existing policy left unchanged", clientKey, name)
}

func wrapPolicyScalar(value string) string {
	encoded, _ := json.Marshal(value)
	return string(encoded)
}

func wrapWorkspaceHasTarget(parsed *policy.Policy, workspaceID, name string) bool {
	for _, workspace := range parsed.Workspaces {
		if workspace.ID != workspaceID {
			continue
		}
		for _, target := range workspace.Targets {
			if target.ID == name {
				return true
			}
		}
	}
	return false
}

func wrapAgentWorkspace(parsed *policy.Policy, clientKey string) (string, bool) {
	for _, agent := range parsed.Agents {
		if agent.ID == clientKey {
			return agent.Workspace, true
		}
	}
	return "", false
}

type wrapRecord struct {
	Config    string          `json:"config"`
	Policy    string          `json:"policy"`
	Original  json.RawMessage `json:"original"`
	Installed json.RawMessage `json:"installed"`
}
type wrapState struct {
	Version int                              `json:"version"`
	Wrapped map[string]map[string]wrapRecord `json:"wrapped"`
}

func loadOrCreateWrapState(path string) (wrapState, error) {
	state := wrapState{Version: 1, Wrapped: map[string]map[string]wrapRecord{}}
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return state, nil
	}
	if err != nil {
		return state, err
	}
	state = wrapState{}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&state); err != nil {
		return state, fmt.Errorf("invalid dedicated wrap state (do not reuse import state): %w", err)
	}
	if decoder.Decode(new(any)) != io.EOF {
		return state, fmt.Errorf("trailing data in wrap state")
	}
	if state.Version != 1 || state.Wrapped == nil {
		return state, fmt.Errorf("unsupported wrap state; use a dedicated wrap state file")
	}
	for _, records := range state.Wrapped {
		for _, record := range records {
			var original, installed map[string]any
			if !filepath.IsAbs(record.Config) || !filepath.IsAbs(record.Policy) || json.Unmarshal(record.Original, &original) != nil || json.Unmarshal(record.Installed, &installed) != nil || original == nil || installed == nil {
				return state, fmt.Errorf("invalid wrap recovery record")
			}
		}
	}
	return state, nil
}
func saveWrapState(path string, state wrapState, write wrapWriteFunc) error {
	encoded, err := json.MarshalIndent(state, "", "  ")
	if err != nil {
		return err
	}
	return write(path, encoded)
}
func defaultWrapStatePath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".harbor", "wrap-state.json")
}

func stringArgs(raw any) []string {
	values, _ := raw.([]any)
	out := make([]string, 0, len(values))
	for _, value := range values {
		if text, ok := value.(string); ok {
			out = append(out, text)
		}
	}
	return out
}

func defaultWrapBin() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".harbor", "bin", "harbor-wrap")
}

func defaultPolicyPath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".harbor", "harbor.yaml")
}
