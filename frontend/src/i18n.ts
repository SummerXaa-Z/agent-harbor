export function normalizeLanguage(value?: string | null): Language {
  const normalized = value?.toLowerCase()
  if (normalized?.startsWith("zh")) {
    return "zh-CN"
  }
  if (normalized?.startsWith("en")) {
    return "en"
  }
  return fallbackLanguage
}

export function resolveInitialLanguage(storedLanguage?: string | null, browserLanguages: string[] = []): Language {
  if (storedLanguage) {
    return normalizeLanguage(storedLanguage)
  }
  return normalizeLanguage(browserLanguages[0])
}

export function translationKeys(language: Language): string[] {
  return Object.keys(translations[language]).sort()
}

export function createTranslator(language: Language) {
  return (key: string, fallback?: string): string => {
    return translations[language][key] ?? translations[fallbackLanguage][key] ?? fallback ?? key
  }
}
