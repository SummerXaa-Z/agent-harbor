#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
OUTPUT_DIR="${AGENT_HARBOR_EVALUATION_OUTPUT_DIR:-${TMPDIR:-/tmp}/agent-harbor-evaluation-readiness}"

usage() {
  cat <<'EOF'
Usage: scripts/evaluation-readiness.sh [--output-dir PATH]

Generate a small external-evaluator pack for the AgentHarbor developer preview.
The pack contains a walkthrough, a feedback log, and acceptance report notes.

Environment:
  AGENT_HARBOR_EVALUATION_OUTPUT_DIR  Default output directory override.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --output-dir)
      if [[ $# -lt 2 || -z "${2:-}" ]]; then
        echo "--output-dir requires a path" >&2
        exit 2
      fi
      OUTPUT_DIR="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

mkdir -p "$OUTPUT_DIR"

capture_command() {
  local label="$1"
  local output
  shift
  if command -v "$1" >/dev/null 2>&1; then
    output="$("$@" 2>/dev/null | head -n 1 || true)"
    printf '%s%s\n' "$label" "${output:-unavailable}"
  else
    printf '%snot found\n' "$label"
  fi
}

branch="$(git -C "$ROOT_DIR" branch --show-current 2>/dev/null || true)"
commit="$(git -C "$ROOT_DIR" rev-parse --short HEAD 2>/dev/null || true)"
generated_at="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
if [[ -n "$(git -C "$ROOT_DIR" status --short 2>/dev/null || true)" ]]; then
  working_tree="dirty"
else
  working_tree="clean"
fi

cat > "$OUTPUT_DIR/README.md" <<'EOF'
# AgentHarbor Evaluation Readiness Pack

Use this pack when asking a platform engineer, security reviewer, or tenant
administrator to evaluate AgentHarbor from a fresh local checkout.

Start here:

1. Read `fresh-run-checklist.md`.
2. Review `environment-snapshot.md`.
3. Start the product with `make demo`.
4. Follow `docs/product/evaluation-readiness.md` in the repository.
5. Export the production acceptance report from the web console.
6. Record the session in `feedback-log.csv`.
7. Summarize the exported report in `acceptance-report-notes.md`.

Keep secrets out of these files. Record actor names, report digests, blocker
codes, and route names instead of admin keys, agent keys, bearer tokens, or
upstream credentials.
EOF

{
  echo "# Environment Snapshot"
  echo
  echo "- Generated at: ${generated_at}"
  echo "- Branch: ${branch:-unknown}"
  echo "- Commit: ${commit:-unknown}"
  echo "- Working tree: ${working_tree}"
  capture_command "- Go: " go version
  capture_command "- Node: " node --version
  capture_command "- pnpm: " "$ROOT_DIR/scripts/pnpm.sh" --version
} > "$OUTPUT_DIR/environment-snapshot.md"

cat > "$OUTPUT_DIR/fresh-run-checklist.md" <<'EOF'
# Fresh Run Checklist

- Repository was freshly cloned or reset to the reviewed branch.
- `environment-snapshot.md` captured branch, commit, and toolchain versions.
- `make check` passed before the manual walkthrough, or the failure was recorded.
- `make demo` started API, MCP, and web console without hidden local services.
- The evaluator opened `http://127.0.0.1:5174/` without author guidance.
- The evaluator reached Permission Changes from Getting Started or Access Query.
- The evaluator exported a production acceptance report.
- The evaluator recorded time-to-first-report and the first blocker, if any.
EOF

cat > "$OUTPUT_DIR/feedback-log.csv" <<'EOF'
date,evaluator_role,environment,branch,commit,time-to-first-report,result,first_blocker,confusing_term,report_digest,notes
EOF

cat > "$OUTPUT_DIR/acceptance-report-notes.md" <<'EOF'
# Acceptance Report Notes

## Session

- Evaluator role:
- Branch:
- Commit:
- Start time:
- End time:
- time-to-first-report:
- Result: ready / needs review / blocked

## Report Reference

- Exported file:
- Report digest:
- Report digest algorithm:
- Generated by:
- Generated at:

## Journey Evidence

- Permission package:
- Tenant / workspace:
- Caller / target:
- Approval record:
- Application record:
- Runtime allow record:
- Runtime deny record:
- Audit record:

## Feedback

- First blocker:
- Confusing term:
- Missing instruction:
- Suggested product fix:
EOF

cat > "$OUTPUT_DIR/evaluator-handoff.md" <<'EOF'
# Evaluator Handoff

You are evaluating AgentHarbor as a developer preview. The goal is to decide
whether a new evaluator can understand and complete the permission-change
journey without author guidance.

Run:

```bash
make demo
```

Then open:

```text
http://127.0.0.1:5174/
```

Your task is complete when you export a production acceptance report and can
answer these questions:

- Who received access?
- Which permission package was applied?
- Which capability was allowed?
- Which capability was denied?
- Which report digest should a reviewer compare?
EOF

cat <<EOF
AgentHarbor evaluation readiness pack generated.

Output directory:
  $OUTPUT_DIR

Recommended next command:
  make demo

Review guide:
  docs/product/evaluation-readiness.md
EOF
